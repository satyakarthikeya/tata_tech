"""Export test cases as a standalone pytest file (raw UDS request/response bytes).

Every byte in the exported file is copied from the :class:`TestCase` (which in
turn came from templates + the rules-engine oracle, or from the gold set); the
exporter never computes protocol bytes itself.

The generated file runs in two modes, chosen by ``UDS_EXPORT_TRANSPORT``:

- ``inprocess`` (default): a fresh :class:`SimulatedEcu` per test, called through
  :class:`InProcessTransport`, with an injected clock (``advance_time`` steps
  move it deterministically).
- ``can``: the same simulator served by :class:`EcuCanServer` on a python-can
  virtual bus; the tester side is ``udsoncan``'s ``PythonIsoTpConnection``
  sending the raw request bytes and waiting for raw response frames. Tests with
  an ``advance_time`` step are **skipped** in CAN mode (the server uses the wall
  clock; real sleeping would add >10 s per S3/lockout test), with a skip reason.

Environment/DTC set-up steps call the simulator's injection API directly in
both modes (the ECU object lives in the test process).
"""

from __future__ import annotations

import re
from pathlib import Path

from uds_assistant.testgen.model import TestCase

SAFETY_BANNER = "FOR SIMULATOR OR APPROVED LAB BENCH ONLY. NEVER RUN AGAINST A PRODUCTION VEHICLE."

_HEADER = '''"""Exported UDS test cases ({count} tests) - generated by uds_assistant.export.to_pytest.

Request/response bytes are copied verbatim from the TestCase objects (templates +
rules-engine oracle, or the hand-written gold set). The ECU spec is SYNTHETIC.

!!! {banner} !!!
Safety: the file refuses to run unless the CAN interface is "virtual"
(UDS_CAN_INTERFACE, default "virtual"); set UDS_ALLOW_LAB_BENCH=1 to override on an
approved bench.

Run:   python -m pytest {filename} -q
Mode:  UDS_EXPORT_TRANSPORT=inprocess (default) | can  (python-can virtual bus +
       udsoncan PythonIsoTpConnection; tests with time-advance steps are skipped).
Spec:  UDS_SPEC_PATH overrides the spec file (default: <repo>/data/bcm_spec.yaml).
"""

from __future__ import annotations

import itertools
import os
import sys
import time
from pathlib import Path

import pytest


def _ensure_package_importable() -> None:
    try:
        import uds_assistant  # noqa: F401
        return
    except ImportError:
        pass
    candidates = [os.environ.get("UDS_REPO_ROOT", ""), *map(str, Path(__file__).resolve().parents)]
    for root in candidates:
        if root and (Path(root) / "uds_assistant" / "__init__.py").exists():
            sys.path.insert(0, root)
            return
    raise ImportError("uds_assistant not importable; set UDS_REPO_ROOT to the repository root")


CAN_INTERFACE = os.environ.get("UDS_CAN_INTERFACE", "virtual").strip().lower()
if CAN_INTERFACE != "virtual" and os.environ.get("UDS_ALLOW_LAB_BENCH") != "1":
    pytest.exit(
        f"Refusing to run: CAN interface is {{CAN_INTERFACE!r}}, not 'virtual'. "
        "These tests are for the simulator or an approved lab bench only and must never run "
        "against a production vehicle. On an approved bench set UDS_ALLOW_LAB_BENCH=1.",
        returncode=2,
    )

_ensure_package_importable()

import uds_assistant
from uds_assistant.simulator import EcuCanServer, InProcessTransport, SimulatedEcu
from uds_assistant.spec.schema import load_spec

TRANSPORT = os.environ.get("UDS_EXPORT_TRANSPORT", "inprocess").strip().lower()
SPEC_PATH = Path(
    os.environ.get(
        "UDS_SPEC_PATH",
        str(Path(uds_assistant.__file__).resolve().parents[1] / "data" / "bcm_spec.yaml"),
    )
)
SPEC = load_spec(SPEC_PATH)
CAN_RESPONSE_TIMEOUT_S = 2.0
CAN_SILENCE_WAIT_S = 0.3
_channels = itertools.count()


def _apply_setup(ecu, step):
    if step[0] == "env":
        ecu.set_environment(vehicle_speed_kph=step[1], nvm_write_fault=step[2])
    elif step[0] == "dtc":
        ecu.set_dtc_status(step[1], step[2])


def _check(index, request_hex, expected, actual):
    assert actual == expected, (
        f"step {{index}}: request {{request_hex}} expected {{expected}}, got {{actual}}"
    )


def _run_inprocess(steps):
    ecu = SimulatedEcu(SPEC)
    transport = InProcessTransport(ecu)
    now_ms = 0
    for index, step in enumerate(steps):
        if step[0] == "send":
            _, request_hex, expected, max_ms = step
            start = time.perf_counter()
            frames = transport.send(bytes.fromhex(request_hex), now_ms=now_ms)
            elapsed_ms = (time.perf_counter() - start) * 1000.0
            _check(index, request_hex, expected, [f.hex() for f in frames])
            if max_ms is not None:
                assert elapsed_ms <= max_ms, f"step {{index}}: {{elapsed_ms:.2f}} ms > {{max_ms}} ms"
        elif step[0] == "advance":
            now_ms += step[1]
        else:
            _apply_setup(ecu, step)


def _can_exchange(conn, request, expect_silence):
    conn.empty_rxqueue()
    conn.send(request)
    frames = []
    timeout = CAN_SILENCE_WAIT_S if expect_silence else CAN_RESPONSE_TIMEOUT_S
    while True:
        frame = conn.wait_frame(timeout=timeout)
        if frame is None:
            return frames
        frame = bytes(frame)
        frames.append(frame)
        if not (len(frame) == 3 and frame[0] == 0x7F and frame[2] == 0x78):
            return frames


def _run_can(steps):
    import can
    from udsoncan.connections import PythonIsoTpConnection

    from uds_assistant.simulator.transport import (
        ECU_TO_TESTER_ID,
        TESTER_TO_ECU_ID,
        make_isotp_stack,
    )

    if any(step[0] == "advance" for step in steps):
        pytest.skip("time-advance step: needs an injected clock (run in inprocess mode)")
    ecu = SimulatedEcu(SPEC)
    channel = f"uds_export_{{os.getpid()}}_{{next(_channels)}}_{{time.monotonic_ns()}}"
    with EcuCanServer(ecu, channel=channel):
        bus = can.Bus(interface=CAN_INTERFACE, channel=channel, receive_own_messages=False)
        notifier = can.Notifier(bus, [], timeout=0.05)
        stack = make_isotp_stack(bus, notifier, rx_id=ECU_TO_TESTER_ID, tx_id=TESTER_TO_ECU_ID)
        conn = PythonIsoTpConnection(stack)
        conn.open()
        try:
            for index, step in enumerate(steps):
                if step[0] == "send":
                    _, request_hex, expected, _max_ms = step
                    frames = _can_exchange(conn, bytes.fromhex(request_hex), not expected)
                    _check(index, request_hex, expected, [f.hex() for f in frames])
                else:
                    _apply_setup(ecu, step)
        finally:
            conn.close()
            notifier.stop()
            bus.shutdown()


def run_steps(steps):
    """Execute one exported test's steps on the selected transport."""
    if TRANSPORT == "can":
        _run_can(steps)
    else:
        _run_inprocess(steps)
'''


def _py_ident(test_id: str) -> str:
    ident = re.sub(r"[^0-9a-zA-Z_]", "_", test_id)
    if not ident or ident[0].isdigit():
        ident = "t_" + ident
    return ident


def _steps_literal(test: TestCase) -> list[str]:
    lines: list[str] = []
    for step in test.steps:
        if step.kind == "send":
            lines.append(
                f"        ({'send'!r}, {step.request_hex!r}, {step.expected_responses_hex!r}, "
                f"{step.max_response_time_ms!r}),"
            )
        elif step.kind == "advance_time":
            lines.append(f"        ({'advance'!r}, {step.ms!r}),")
        elif step.kind == "set_environment":
            lines.append(
                f"        ({'env'!r}, {step.vehicle_speed_kph!r}, {step.nvm_write_fault!r}),"
            )
        elif step.kind == "set_dtc_status":
            lines.append(f"        ({'dtc'!r}, {step.code!r}, {step.status!r}),")
    return lines


def _safe_comment(text: str) -> str:
    return " ".join(text.split()).replace('"""', "'''")


def render_pytest(tests: list[TestCase], filename: str = "exported_test.py") -> str:
    """Render the pytest module source for ``tests`` (see :func:`to_pytest`)."""
    parts = [_HEADER.format(count=len(tests), filename=filename, banner=SAFETY_BANNER)]
    used: set[str] = set()
    for test in tests:
        name = "test_" + _py_ident(test.id)
        base, n = name, 2
        while name in used:
            name, n = f"{base}_{n}", n + 1
        used.add(name)
        doc = _safe_comment(f"{test.title} [{test.category}; template={test.template_id}; "
                            f"requirements={','.join(test.requirement_ids) or '-'}]")
        pre = "; ".join(test.preconditions) or "-"
        crit = test.pass_criteria or "-"
        body = [
            "",
            "",
            f"def {name}():",
            f'    """{doc}',
            "",
            f"    Preconditions: {_safe_comment(pre)}",
            f"    Pass criteria: {_safe_comment(crit)}",
            '    """',
            "    run_steps([",
            *_steps_literal(test),
            "    ])",
        ]
        parts.append("\n".join(body))
    return "".join(parts) + "\n"


def to_pytest(tests: list[TestCase], path: str | Path) -> Path:
    """Write ``tests`` as a standalone pytest file at ``path`` and return the path.

    The file depends only on pytest and the ``uds_assistant`` simulator/spec
    loader (located via import, ``UDS_REPO_ROOT``, or the file's parent dirs);
    CAN mode additionally needs python-can, can-isotp and udsoncan.
    """
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_pytest(tests, p.name), encoding="utf-8")
    return p
