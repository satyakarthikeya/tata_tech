"""Export test cases as CAPL test-case templates (UNVERIFIED — never compiled in CANoe).

Each :class:`TestCase` becomes one ``testcase`` function that builds the raw
request bytes into a ``diagRequest``, sends it, waits with
``testWaitForDiagResponse`` and compares the raw response bytes. Time-advance
steps become ``testWaitForTimeout``; simulator-only set-up steps (vehicle speed,
NVM fault, DTC status injection) become explicit "not generated by this template"
notes for the bench engineer. CANoe is not available in this project, so the output is labelled a
template.
"""

from __future__ import annotations

import re
from pathlib import Path

from uds_assistant.testgen.model import TestCase

CAPL_BANNER = "UNVERIFIED TEMPLATE — not compiled or run in CANoe"
SAFETY_BANNER = "FOR SIMULATOR OR APPROVED LAB BENCH ONLY. NEVER RUN AGAINST A PRODUCTION VEHICLE."
NOT_GENERATED = (
    "NOTE: not generated by this template: configure in your CANoe environment"
)

_PRELUDE = """/*
 * {banner}
 * {safety}
 *
 * Generated by uds_assistant.export.to_capl from {count} test case(s).
 * Request/response bytes are copied verbatim from the test cases (templates +
 * rules-engine oracle, or the hand-written gold set). The ECU spec is SYNTHETIC.
 * Adapt the diagnostic target / CDD binding before use; review every test.
 *
 * NOTE: not generated by this template: configure in your CANoe environment:
 *   - the diagnostic target (ECU qualifier / CDD / ODX) the diagRequest objects bind to;
 *   - tester-side session keep-alive (TesterPresent) and the S3 timer behaviour;
 *   - handling of 7F xx 78 response-pending frames (the diag layer must absorb them);
 *   - bench set-up for the simulator-only steps (vehicle speed, NVM fault, DTC injection),
 *     which appear below as "not generated" notes;
 *   - the security-access seed/key algorithm (keys here are fixed bytes for the SYNTHETIC ECU);
 *   - test-module configuration (test environment, verdict handling, report generation).
 */

includes
{{
}}

variables
{{
  const dword kP2TimeoutMs = 2000;      // generous tester-side timeout per request
  const dword kSilenceWaitMs = 300;     // wait used when no response is expected
}}

/* Send raw request bytes and compare the final response with the expected bytes.
 * expectedLen == 0 means "no response expected" (suppressed positive response). */
int SendAndCheck(byte req[], dword reqLen, byte expected[], dword expectedLen, char stepName[])
{{
  diagRequest * rawReq;
  diagResponse * rawResp;
  dword i;
  long waitResult;
  byte actual[4095];
  long actualLen;

  diagResize(rawReq, reqLen);
  for (i = 0; i < reqLen; i++)
    diagSetPrimitiveByte(rawReq, i, req[i]);
  diagSendRequest(rawReq);

  if (expectedLen == 0)
  {{
    waitResult = testWaitForDiagResponse(rawReq, kSilenceWaitMs);
    if (waitResult == 1)
    {{
      testStepFail(stepName, "Unexpected response (positive response should be suppressed)");
      return 0;
    }}
    testStepPass(stepName, "No response, as expected");
    return 1;
  }}

  waitResult = testWaitForDiagResponse(rawReq, kP2TimeoutMs);
  if (waitResult != 1)
  {{
    testStepFail(stepName, "No response within timeout");
    return 0;
  }}
  diagGetLastResponse(rawReq, rawResp);
  actualLen = diagGetPrimitiveSize(rawResp);
  if (actualLen != expectedLen)
  {{
    testStepFail(stepName, "Response length %d, expected %d", actualLen, expectedLen);
    return 0;
  }}
  for (i = 0; i < expectedLen; i++)
  {{
    actual[i] = diagGetPrimitiveByte(rawResp, i);
    if (actual[i] != expected[i])
    {{
      testStepFail(stepName, "Byte %d is 0x%02X, expected 0x%02X", i, actual[i], expected[i]);
      return 0;
    }}
  }}
  testStepPass(stepName, "Response matches");
  return 1;
}}
"""


def _capl_ident(test_id: str) -> str:
    ident = re.sub(r"[^0-9a-zA-Z_]", "_", test_id)
    return "TC_" + ident


def _byte_array(name: str, data: bytes) -> str:
    if not data:
        return f"  byte {name}[1] = {{0x00}};  // unused (no bytes)"
    values = ", ".join(f"0x{b:02X}" for b in data)
    return f"  byte {name}[{len(data)}] = {{{values}}};"


def _comment(text: str) -> str:
    return " ".join(text.replace("*/", "* /").split())


def render_capl(tests: list[TestCase]) -> str:
    """Render the CAPL template source for ``tests`` (see :func:`to_capl`)."""
    out = [_PRELUDE.format(banner=CAPL_BANNER, safety=SAFETY_BANNER, count=len(tests))]
    used: set[str] = set()
    for test in tests:
        name = _capl_ident(test.id)
        base, n = name, 2
        while name in used:
            name, n = f"{base}_{n}", n + 1
        used.add(name)
        lines = [
            "",
            f"/* {_comment(test.title)}",
            (f" * category={test.category} template={test.template_id} "
            f"requirements={','.join(test.requirement_ids) or '-'} origin={test.origin}"),
            f" * Preconditions: {_comment('; '.join(test.preconditions)) or '-'}",
            f" * Pass criteria: {_comment(test.pass_criteria) or '-'}",
            " */",
            f"testcase {name}()",
            "{",
            f'  testCaseTitle("{test.id}", "{_comment(test.title).replace(chr(34), chr(39))}");',
        ]
        for i, step in enumerate(test.steps):
            if step.kind == "send":
                req = step.request_bytes
                lines.append(f"  // step {i}: {_comment(step.description) or 'send request'}")
                lines.append("  {")
                lines.append("  " + _byte_array(f"req{i}", req))
                frames = step.expected_response_bytes
                if not frames:
                    lines.append(f'    SendAndCheck(req{i}, {len(req)}, req{i}, 0, "step {i}");')
                else:
                    final = frames[-1]
                    if len(frames) > 1:
                        pending = " ".join(f"{f.hex(' ').upper()}" for f in frames[:-1])
                        lines.append(
                            f"    // interim frame(s) expected first: {pending} "
                            "(response pending; handled by the diag layer)"
                        )
                    lines.append("  " + _byte_array(f"exp{i}", final))
                    lines.append(
                        f'    SendAndCheck(req{i}, {len(req)}, exp{i}, {len(final)}, "step {i}");'
                    )
                lines.append("  }")
            elif step.kind == "advance_time":
                lines.append(f"  // step {i}: {_comment(step.description) or 'wait'}")
                lines.append(f"  testWaitForTimeout({step.ms});")
            elif step.kind == "set_environment":
                lines.append(
                    f"  // step {i}: {NOT_GENERATED}. Missing: bench set-up of "
                    f"vehicle_speed_kph={step.vehicle_speed_kph} "
                    f"nvm_write_fault={step.nvm_write_fault} "
                    "(simulator-only injection; use a signal/environment variable or a bench fixture)"
                )
            elif step.kind == "set_dtc_status":
                lines.append(
                    f"  // step {i}: {NOT_GENERATED}. Missing: a way to put DTC {step.code} "
                    f"into status 0x{step.status:02X} (simulator-only fault injection)"
                )
        lines.append("}")
        out.append("\n".join(lines))
    names = sorted(used)
    out.append(
        "\n\n/* Test module entry point: runs every exported test case. */\n"
        "void MainTest()\n{\n" + "".join(f"  {n}();\n" for n in names) + "}\n"
    )
    return "\n".join(out)


def to_capl(tests: list[TestCase], path: str | Path) -> Path:
    """Write ``tests`` as CAPL test-case templates to ``path`` and return the path.

    The file starts with the banner ``UNVERIFIED TEMPLATE — not compiled or run
    in CANoe``; it has not been compiled or executed.
    """
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_capl(tests), encoding="utf-8")
    return p
